import pandas as pd

IN, OUT = 'Поступление', 'Списание'

# (категория, регулярное выражение, к какому направлению применимо)
# Порядок = приоритет: срабатывает ПЕРВОЕ подходящее правило.
RULES = [
    ('Перевод собственных средств', r'перевод собственных|собственных средств', None),
    ('Налоги',        r'\bенп\b|единый налоговый|налог|ндфл|страховые взнос|взносы на|\bусн\b|штраф|\bпени\b', OUT),
    ('Зарплата',      r'зарплат|заработн|аванс|отпускн|больничн|оплата труда', OUT),
    ('Аренда',        r'аренд|помещени|недвижим', OUT),
    ('Кредиты/Лизинг', r'кредит|лизинг|займ|процент|гашение|основной долг', None),
    ('Выручка (Эквайринг)', r'эквайринг|поступление по картам|\bсбп\b', IN),
    ('Выручка (Безнал)',    r'оплата по счету|оплата по договору|оплата по упд|поступление|оплата за товар|за услуги', IN),
    ('Банковские комиссии', r'комисси|ведение счета|обслуживание счета', OUT),
    ('Закупки/Поставщики',  r'поставк|поставщик|закупк|товар|материал|сырье|запчаст|ремонт|оплата по |оплата за |услуг', OUT),
]


def categorize_operations(df):
    print("Категоризация операций...")

    purpose = df['payment_purpose'].str.lower()
    df['category'] = 'Не определено'

    for cat, pattern, direction in RULES:
        mask = purpose.str.contains(pattern, regex=True, na=False)
        mask &= df['category'] == 'Не определено'      # первое совпадение выигрывает
        if direction:
            mask &= df['direction'] == direction       # выручка только для поступлений, закупки только для списаний
        df.loc[mask, 'category'] = cat

    df.loc[(df['direction'] == IN) & (df['category'] == 'Не определено'), 'category'] = 'Выручка (Прочее)'
    df.loc[(df['direction'] == OUT) & (df['category'] == 'Не определено'), 'category'] = 'Прочие расходы'

    print("Распределение по категориям:")
    print(df['category'].value_counts())
    return df


if __name__ == "__main__":
    df = pd.read_pickle('clean_operations.pkl')
    df = categorize_operations(df)
    df.to_pickle('categorized_operations.pkl')
    print("Готово!")
